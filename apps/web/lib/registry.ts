import { ASSETS as SDK_ASSETS, type AssetSymbol } from "@versus/sdk/browser";
import type { AssetKind } from "./types";

export interface Asset {
  symbol: string;
  name: string;
  /** Short fight-card name used in headlines. Multi-word names carry a non-breaking space so they never wrap. */
  label: string;
  pairSymbol: string;
  kind: AssetKind;
  /** Pyth price feed id (hex) and its display name. */
  feedId: string;
  feedName: string;
  /** Shares outstanding for CapCompare templates; null for crypto. */
  shares: number | null;
  /** Reference price used by demo fixtures and the create-duel preview. */
  refPrice: number;
  /** Mainnet mint of the pair token (xStocks / wrapped) and the devnet mock. */
  mint: string;
  mockMint: string | null;
  /** Company or project website; the last-resort favicon source for `/api/logo`. */
  domain: string;
}

